// The countries this screen offers, named in the language the page is read in and sorted in it.
// A browser that cannot name a region leaves the code, which is still unambiguous.
export function countryOptions(locale: string): Place[] {
  const names = regionNames(locale);
  return countryCodes
    .map((code) => ({ code, name: names?.of(code) ?? code }))
    .sort((left, right) => left.name.localeCompare(right.name, locale));
}

function regionNames(locale: string): Intl.DisplayNames | null {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' });
  } catch {
    return null;
  }
}
